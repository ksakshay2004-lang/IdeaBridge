import { AlertTriangle, CheckCircle2, ExternalLink, Lightbulb, ShieldAlert, Target, Users, Wallet } from "lucide-react";
import { Bar, BarChart, CartesianGrid, ResponsiveContainer, Tooltip, XAxis, YAxis, Cell } from "recharts";
import type { Evaluation } from "../lib/types";
import { Badge, Card, Notice, ScoreRing } from "./ui";
import { scoreColor, fmtDateTime } from "../lib/utils";

const List = ({ items, icon, tone }: { items: string[]; icon: React.ReactNode; tone: string }) =>
  items.length === 0 ? <p className="text-sm text-slate-400">None identified.</p> :
    <ul className="space-y-2">{items.map((t, i) => <li key={i} className={`flex gap-2 text-sm ${tone}`}><span className="mt-0.5 shrink-0">{icon}</span><span>{t}</span></li>)}</ul>;

const Section = ({ title, children, icon }: { title: string; children: React.ReactNode; icon?: React.ReactNode }) => (
  <Card className="p-5"><h3 className="mb-3 flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-navy-700">{icon}{title}</h3>{children}</Card>
);

export default function ReportView({ evaluation }: { evaluation: Evaluation }) {
  const r = evaluation.report;
  if (!r) return null;
  const demo = r.meta.mode === "demo";
  const chart = r.similar_projects.slice(0, 8).map((s) => ({ name: s.title.length > 26 ? s.title.slice(0, 24) + "…" : s.title, value: s.similarity_pct }));
  return (
    <div className="space-y-5">
      {demo ? (
        <Notice title="DEMO MODE – not generated by an AI model">
          {r.meta.notice} Scores are rule-based estimates; similarity percentages are real vector calculations.
          {r.meta.fallback_reason && <span className="mt-1 block text-xs opacity-80">Reason for fallback: {r.meta.fallback_reason}</span>}
        </Notice>
      ) : (
        <Notice tone="sky" title={`Generated by ${r.meta.provider} · ${r.meta.model}`}>
          AI-generated analysis grounded in retrieved evidence. Treat as decision support, not as a verdict.
        </Notice>
      )}
      <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-slate-500">
        <span>Version {evaluation.version}</span><span>Generated {fmtDateTime(r.meta.generated_at)}</span>
        {evaluation.outdated && <Badge tone="amber">Idea edited since this report</Badge>}
      </div>

      <Card className="p-6">
        <div className="flex flex-wrap items-center justify-around gap-6">
          <ScoreRing value={r.scores.overall} label="Overall" size={110} />
          <ScoreRing value={r.scores.technical_feasibility} label="Technical feasibility" />
          <ScoreRing value={r.scores.market_opportunity} label="Market opportunity" />
          <ScoreRing value={r.scores.innovation_differentiation} label="Innovation / differentiation" />
        </div>
        <div className="mt-5 flex flex-wrap gap-2 text-sm">
          <Badge tone={r.novelty_assessment.level === "high" ? "green" : r.novelty_assessment.level === "low" ? "red" : "amber"}>Novelty: {r.novelty_assessment.level}</Badge>
          <Badge tone="indigo">Development complexity: {r.development_complexity.level}</Badge>
        </div>
      </Card>

      <div className="grid gap-5 md:grid-cols-3">
        <Section title="Idea summary"><p className="text-sm text-slate-700">{r.idea_summary || "—"}</p></Section>
        <Section title="Problem statement"><p className="text-sm text-slate-700">{r.problem_statement || "—"}</p></Section>
        <Section title="Proposed solution"><p className="text-sm text-slate-700">{r.proposed_solution || "—"}</p></Section>
      </div>

      <Section title="Similar existing projects" icon={<Target className="h-4 w-4" />}>
        <p className="mb-3 text-xs text-slate-500">Searched {r.evidence.reference_projects_searched} curated projects, {r.evidence.platform_ideas_searched} platform ideas{r.evidence.research_papers_searched ? ` and ${r.evidence.research_papers_searched} arXiv papers` : ""} using {r.evidence.similarity_method}. {r.evidence.limitation}</p>
        {chart.length > 0 && (
          <div className="mb-4 h-56 w-full" aria-label="Similarity chart">
            <ResponsiveContainer>
              <BarChart data={chart} layout="vertical" margin={{ left: 10, right: 20 }}>
                <CartesianGrid horizontal={false} stroke="#e2e8f0" /><XAxis type="number" domain={[0, 100]} unit="%" fontSize={11} />
                <YAxis type="category" dataKey="name" width={150} fontSize={11} /><Tooltip formatter={(v) => `${v}%`} />
                <Bar dataKey="value" radius={[0, 4, 4, 0]}>{chart.map((c, i) => <Cell key={i} fill={scoreColor(100 - c.value * 1.5)} />)}</Bar>
              </BarChart>
            </ResponsiveContainer>
          </div>
        )}
        <div className="divide-y divide-slate-100">
          {r.similar_projects.map((s) => (
            <div key={s.kind + s.ref_id} className="flex flex-wrap items-start justify-between gap-2 py-3">
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2 text-sm font-medium text-navy-900">
                  {s.url ? <a href={s.url} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1 hover:underline">{s.title}<ExternalLink className="h-3 w-3" /></a> : s.title}
                  <Badge>{s.kind === "reference" ? "existing project" : s.kind === "platform" ? "platform idea" : "research paper"}</Badge>
                  {s.is_competitor && <Badge tone="red">potential competitor</Badge>}
                </div>
                {s.key_differences && <p className="mt-1 text-sm text-slate-600"><span className="font-medium">Key differences:</span> {s.key_differences}</p>}
              </div>
              <span className="text-sm font-semibold tabular-nums text-slate-700">{s.similarity_pct}%</span>
            </div>
          ))}
        </div>
      </Section>

      <div className="grid gap-5 md:grid-cols-2">
        <Section title="Novelty assessment"><p className="text-sm text-slate-700">{r.novelty_assessment.rationale || "—"}</p></Section>
        <Section title="Development complexity"><p className="text-sm text-slate-700">{r.development_complexity.rationale || "—"}</p></Section>
        <Section title="Strengths" icon={<CheckCircle2 className="h-4 w-4 text-emerald-600" />}><List items={r.strengths} icon={<CheckCircle2 className="h-4 w-4 text-emerald-600" />} tone="text-slate-700" /></Section>
        <Section title="Weaknesses" icon={<AlertTriangle className="h-4 w-4 text-amber-600" />}><List items={r.weaknesses} icon={<AlertTriangle className="h-4 w-4 text-amber-600" />} tone="text-slate-700" /></Section>
        <Section title="Risks & limitations" icon={<ShieldAlert className="h-4 w-4 text-rose-600" />}><List items={r.risks} icon={<ShieldAlert className="h-4 w-4 text-rose-600" />} tone="text-slate-700" /></Section>
        <Section title="Recommended improvements" icon={<Lightbulb className="h-4 w-4 text-navy-600" />}><List items={r.recommended_improvements} icon={<Lightbulb className="h-4 w-4 text-navy-600" />} tone="text-slate-700" /></Section>
        <Section title="Potential target users" icon={<Users className="h-4 w-4" />}><div className="flex flex-wrap gap-2">{r.target_users.map((t) => <Badge key={t} tone="indigo">{t}</Badge>)}</div></Section>
        <Section title="Possible revenue models" icon={<Wallet className="h-4 w-4" />}><div className="flex flex-wrap gap-2">{r.revenue_models.map((t) => <Badge key={t} tone="green">{t}</Badge>)}</div></Section>
      </div>

      {r.competitors.length > 0 && (
        <Section title="Potential competitors (from retrieved evidence)">
          <ul className="space-y-1 text-sm">{r.competitors.map((c) => <li key={c.ref_id}>{c.url ? <a className="text-navy-700 hover:underline" href={c.url} target="_blank" rel="noopener noreferrer">{c.name}</a> : c.name} <span className="text-slate-400">· {c.similarity_pct}% similar</span></li>)}</ul>
        </Section>
      )}
      <Section title="Overall evaluation"><p className="text-sm leading-relaxed text-slate-700">{r.overall_evaluation || "—"}</p></Section>
    </div>
  );
}
